// Работа 1. Начало работы с React — Пример «Список дел»

import React, { useState } from 'react'; // подключаем React и useState

function TodoList() { // создаём компонент «Список дел»
  const [todos, setTodos] = useState(['Выучить React', 'Написать приложение']); // память для списка дел: сначала в нём 2 дела; setTodos — заменить список новым
  const [inputValue, setInputValue] = useState(''); // память для текста в поле ввода: сначала пусто

  const addTodo = () => { // функция «добавить дело», сработает при нажатии кнопки «Добавить»
    if (inputValue.trim()) { // trim() убирает пробелы по краям; если текст НЕ пустой — добавляем
      // Обновляем состояние, добавляя новую задачу
      setTodos([...todos, inputValue]); // НОВЫЙ массив: все старые дела (...todos) + новый текст в конце
      // Очищаем поле ввода
      setInputValue(''); // записываем пустую строку — поле очищается
    } // конец if
  }; // конец функции addTodo

  return ( // что показать на экране
    <div> {/* общая обёртка */}
      <h1>Мой список дел</h1> {/* заголовок */}
      <div> {/* блок с полем ввода и кнопкой */}
        <input // поле ввода
          type="text" // поле для обычного текста
          value={inputValue} // в поле всегда показан текст из памяти inputValue
          onChange={(e) => setInputValue(e.target.value)} // Обновляем состояние при каждом нажатии клавиши (e.target.value — текст в поле)
        /> {/* конец поля ввода */}
        <button onClick={addTodo}>Добавить</button> {/* кнопка «Добавить»: при клике вызывает addTodo */}
      </div> {/* конец блока с полем и кнопкой */}
      <ul> {/* начало списка */}
        {/* Маппим массив задач в массив JSX-элементов <li> */}
        {todos.map((todo, index) => ( // проходим по каждому делу: todo — текст дела, index — его номер (0, 1, 2...)
          <li key={index}>{todo}</li> // для каждого дела — пункт списка; key — обязательная метка для элементов списка
        ))} {/* конец map */}
      </ul> {/* конец списка */}
    </div> // конец обёртки
  ); // конец return
} // конец компонента TodoList

export default TodoList; // отдаём компонент наружу
