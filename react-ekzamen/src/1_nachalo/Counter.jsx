// Работа 1. Начало работы с React — Пример «Кнопка-счётчик»

// 1. Импортируем React и хуки
import React, { useState } from 'react'; // подключаем React и функцию useState (она даёт компоненту «память»)

// 2. Создаем функциональный компонент
function Counter() { // создаём компонент Counter — это обычная функция, имя с большой буквы
  // 3. Объявляем состояние "count" с начальным значением 0
  // setCount — это функция для его изменения
  const [count, setCount] = useState(0); // count — текущее число (сначала 0), setCount — функция, чтобы его поменять

  // 4. Функция-обработчик нажатия на кнопку
  const increment = () => { // создаём функцию increment («увеличить»), она сработает при клике
    setCount(count + 1); // Обновляем состояние: новое число = старое + 1
    // После вызова setCount React ПЕРЕРИСОВЫВАЕТ этот компонент автоматически!
  }; // конец функции increment

  // 5. Возвращаем JSX - описание того, что мы хотим видеть
  return ( // дальше то, что компонент покажет на экране
    <div> {/* общая обёртка: в return должен быть один главный тег */}
      <p>Вы нажали {count} раз(а)</p> {/* абзац; вместо {count} подставится текущее число */}
      {/* При клике вызываем функцию increment */}
      <button onClick={increment}>Нажми на меня</button> {/* кнопка; onClick={increment} — при клике вызвать increment (пишем БЕЗ скобок) */}
    </div> // конец обёртки
  ); // конец return
} // конец компонента Counter

// 6. Экспортируем компонент
export default Counter; // разрешаем другим файлам взять этот компонент (import Counter from './Counter')
