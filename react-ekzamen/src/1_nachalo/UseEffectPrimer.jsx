// Работа 1. Начало работы с React — Хуки useState и useEffect
// В методичке дан только кусочек кода с useEffect, поэтому он вставлен
// в знакомый компонент-счётчик, чтобы его можно было запустить.

import React, { useState, useEffect } from 'react'; // подключаем React, useState и useEffect

function Counter() { // компонент-счётчик
  const [count, setCount] = useState(0); // "Запомни, что count сейчас равен 0"

  // "Сделай это после того, как компонент отобразится на экране"
  useEffect(() => { // useEffect выполняет код ПОСЛЕ того, как компонент появился на экране
    document.title = `Вы нажали ${count} раз`; // меняем название вкладки браузера, ${count} подставляет число
  }, [count]); // "Сделай это снова, если значение count изменилось"

  return ( // что показать на экране
    <div> {/* обёртка */}
      <p>Вы нажали {count} раз(а)</p> {/* текст с числом */}
      <button onClick={() => setCount(count + 1)}>Нажми на меня</button> {/* при клике увеличиваем число на 1 */}
      <p>Посмотри на название вкладки браузера — оно меняется вместе с числом.</p> {/* подсказка */}
    </div> // конец обёртки
  ); // конец return
} // конец компонента

export default Counter; // отдаём компонент наружу
