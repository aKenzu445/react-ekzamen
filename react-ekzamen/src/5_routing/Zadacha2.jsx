// Работа 5. Роутинг — Задача 2. Добавляем меню
// Переходы между страницами «Главная», «Мастера», «Запись» через Link.
// Navbar — решение из методички. Home и App — из задачи 1 (Navbar должен быть внутри BrowserRouter).

import { BrowserRouter, Routes, Route, Link } from "react-router-dom"; // части роутинга + Link (ссылка)

function Home() { // главная страница
  return <h1>Добро пожаловать в салон "Golden Scissors"!</h1>; // приветствие
} // конец Home

function Navbar() { // компонент меню (навигации)
  return ( // что показать
    <nav> {/* тег для меню навигации */}
      <Link to="/">Главная</Link> |{" "} {/* ссылка на "/" (без перезагрузки страницы); | — разделитель; {" "} — пробел */}
      <Link to="/masters">Мастера</Link> |{" "} {/* ссылка на страницу мастеров */}
      <Link to="/booking">Запись</Link> {/* ссылка на страницу записи */}
    </nav> // конец меню
  ); // конец return
} // конец Navbar

function App() { // главный компонент
  return ( // что показать
    <BrowserRouter> {/* включаем роутинг */}
      <Navbar /> {/* меню — стоит вне Routes, поэтому видно на всех страницах */}
      <Routes> {/* список маршрутов */}
        <Route path="/" element={<Home />} /> {/* "/" -> главная */}
      </Routes> {/* конец списка */}
    </BrowserRouter> // конец роутинга
  ); // конец return
} // конец App

export default App; // отдаём наружу

// Ожидаемый результат: меню со ссылками. Страниц «Мастера» и «Запись» пока нет — они появятся в задачах 3 и 4.
