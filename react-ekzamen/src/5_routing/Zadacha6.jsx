// Обработка маршрутов, которых нет в системе.

import { useState } from "react"; // useState для формы записи
import { BrowserRouter, Routes, Route, Link } from "react-router-dom"; // части роутинга

function Home() { // главная страница
  return <h1>Добро пожаловать в салон "Golden Scissors"!</h1>; // приветствие
} // конец Home

function Navbar() { // меню
  return ( // что показать
    <nav> {/* меню */}
      <Link to="/">Главная</Link> |{" "} {/* ссылка на главную */}
      <Link to="/masters">Мастера</Link> |{" "} {/* ссылка на мастеров */}
      <Link to="/booking">Запись</Link> |{" "} {/* ссылка на запись */}
      <Link to="/abc">Несуществующая страница</Link> {/* для проверки 404 (в методичке этой ссылки нет — просто чтобы проверить) */}
    </nav> // конец меню
  ); // конец return
} // конец Navbar

function Masters() { // страница мастеров
  const masters = [ // массив мастеров
    { name: "Анна", skill: "Парикмахер-стилист" }, // мастер
    { name: "Игорь", skill: "Барбер" }, // мастер
    { name: "Мария", skill: "Колорист" }, // мастер
  ]; // конец массива

  return ( // что показать
    <div> {/* обёртка */}
      <h2>Наши мастера</h2> {/* заголовок */}
      <ul> {/* список */}
        {masters.map((m, i) => ( // для каждого мастера
          <li key={i}>{m.name} — {m.skill}</li> // пункт: имя — специализация
        ))} {/* конец map */}
      </ul> {/* конец списка */}
    </div> // конец обёртки
  ); // конец return
} // конец Masters

function Booking() { // страница записи с формой (задача 5)
  const [name, setName] = useState(""); // память для имени
  const [date, setDate] = useState(""); // память для даты

  return ( // что показать
    <div> {/* обёртка */}
      <h2>Онлайн-запись</h2> {/* заголовок */}
      <input // поле для имени
        type="text" // текст
        placeholder="Ваше имя" // подсказка
        value={name} // значение из памяти
        onChange={(e) => setName(e.target.value)} // при вводе обновляем память
      /> {/* конец поля */}
      <input // поле для даты
        type="date" // календарь
        value={date} // значение из памяти
        onChange={(e) => setDate(e.target.value)} // при выборе обновляем память
      /> {/* конец поля */}
      <button onClick={() => alert(`${name}, вы записаны на ${date}`)}> {/* окно с подтверждением */}
        Подтвердить {/* текст на кнопке */}
      </button> {/* конец кнопки */}
    </div> // конец обёртки
  ); // конец return
} // конец Booking

function NotFound() { // компонент «Страница не найдена»
  return <h2>404 — Страница не найдена</h2>; // сообщение (404 — стандартный код ошибки «не найдено»)
} // конец NotFound

function App() { // главный компонент
  return ( // что показать
    <BrowserRouter> {/* включаем роутинг */}
      <Navbar /> {/* меню */}
      <Routes> {/* список маршрутов */}
        <Route path="/" element={<Home />} /> {/* главная */}
        <Route path="/masters" element={<Masters />} /> {/* мастера */}
        <Route path="/booking" element={<Booking />} /> {/* запись */}
        <Route path="*" element={<NotFound />} /> {/* * — ЛЮБОЙ другой адрес: если выше ничего не подошло — показать NotFound */}
      </Routes> {/* конец списка */}
    </BrowserRouter> // конец роутинга
  ); // конец return
} // конец App

export default App; // отдаём наружу

