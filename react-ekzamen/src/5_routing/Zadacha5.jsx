// Работа 5. Роутинг — Задача 5. Страница записи с формой
// На странице /booking клиент вводит имя и дату записи. Booking заменяет простую версию из задачи 4.

import { useState } from "react"; // берём useState для памяти
import { BrowserRouter, Routes, Route, Link } from "react-router-dom"; // части роутинга

function Home() { // главная страница
  return <h1>Добро пожаловать в салон "Golden Scissors"!</h1>; // приветствие
} // конец Home

function Navbar() { // меню
  return ( // что показать
    <nav> {/* меню */}
      <Link to="/">Главная</Link> |{" "} {/* ссылка на главную */}
      <Link to="/masters">Мастера</Link> |{" "} {/* ссылка на мастеров */}
      <Link to="/booking">Запись</Link> {/* ссылка на запись */}
    </nav> // конец меню
  ); // конец return
} // конец Navbar

function Masters() { // страница мастеров
  const masters = [ // массив мастеров
    { name: "Анна", skill: "Парикмахер-стилист" }, // мастер
    { name: "Игорь", skill: "Барбер" }, // мастер
    { name: "Мария", skill: "Колорист" }, // мастер
  ]; // конец массива

  return ( // что показать
    <div> {/* обёртка */}
      <h2>Наши мастера</h2> {/* заголовок */}
      <ul> {/* список */}
        {masters.map((m, i) => ( // для каждого мастера
          <li key={i}>{m.name} — {m.skill}</li> // пункт: имя — специализация
        ))} {/* конец map */}
      </ul> {/* конец списка */}
    </div> // конец обёртки
  ); // конец return
} // конец Masters

function Booking() { // страница записи с формой
  const [name, setName] = useState(""); // память для имени, сначала пусто
  const [date, setDate] = useState(""); // память для даты, сначала пусто

  return ( // что показать
    <div> {/* обёртка */}
      <h2>Онлайн-запись</h2> {/* заголовок */}
      <input // поле для имени
        type="text" // поле для текста
        placeholder="Ваше имя" // серая подсказка внутри пустого поля
        value={name} // в поле показан текст из памяти name
        onChange={(e) => setName(e.target.value)} // при вводе записываем текст в name
      /> {/* конец поля */}
      <input // поле для даты
        type="date" // поле даты: при клике открывается календарь, дата приходит как "2025-10-25"
        value={date} // показывает дату из памяти
        onChange={(e) => setDate(e.target.value)} // при выборе записываем дату в date
      /> {/* конец поля */}
      <button onClick={() => alert(`${name}, вы записаны на ${date}`)}> {/* при клике alert показывает окно с текстом; имя и дата подставляются в строку */}
        Подтвердить {/* текст на кнопке */}
      </button> {/* конец кнопки */}
    </div> // конец обёртки
  ); // конец return
} // конец Booking

function App() { // главный компонент
  return ( // что показать
    <BrowserRouter> {/* включаем роутинг */}
      <Navbar /> {/* меню */}
      <Routes> {/* список маршрутов */}
        <Route path="/" element={<Home />} /> {/* главная */}
        <Route path="/masters" element={<Masters />} /> {/* мастера */}
        <Route path="/booking" element={<Booking />} /> {/* запись (теперь с формой) */}
      </Routes> {/* конец списка */}
    </BrowserRouter> // конец роутинга
  ); // конец return
} // конец App

export default App; // отдаём наружу

// Пример запуска: имя Анна, дата 2025-10-25 -> окно «Анна, вы записаны на 2025-10-25».
