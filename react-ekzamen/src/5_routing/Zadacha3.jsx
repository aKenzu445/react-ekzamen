// Работа 5. Роутинг — Задача 3. Страница мастеров
// Показать список мастеров салона и их специализацию.
// Masters — решение из методички. Остальное — из задач 1–2 + маршрут /masters, чтобы страницу можно было открыть.

import { BrowserRouter, Routes, Route, Link } from "react-router-dom"; // части роутинга

function Home() { // главная страница
  return <h1>Добро пожаловать в салон "Golden Scissors"!</h1>; // приветствие
} // конец Home

function Navbar() { // меню
  return ( // что показать
    <nav> {/* меню */}
      <Link to="/">Главная</Link> |{" "} {/* ссылка на главную */}
      <Link to="/masters">Мастера</Link> |{" "} {/* ссылка на мастеров */}
      <Link to="/booking">Запись</Link> {/* ссылка на запись */}
    </nav> // конец меню
  ); // конец return
} // конец Navbar

function Masters() { // компонент страницы мастеров
  const masters = [ // массив мастеров
    { name: "Анна", skill: "Парикмахер-стилист" }, // мастер: имя и специализация
    { name: "Игорь", skill: "Барбер" }, // мастер
    { name: "Мария", skill: "Колорист" }, // мастер
  ]; // конец массива

  return ( // что показать
    <div> {/* обёртка */}
      <h2>Наши мастера</h2> {/* заголовок */}
      <ul> {/* список */}
        {masters.map((m, i) => ( // проходим по мастерам: m — мастер, i — номер
          <li key={i}>{m.name} — {m.skill}</li> // пункт списка: «Анна — Парикмахер-стилист»
        ))} {/* конец map */}
      </ul> {/* конец списка */}
    </div> // конец обёртки
  ); // конец return
} // конец Masters

function App() { // главный компонент
  return ( // что показать
    <BrowserRouter> {/* включаем роутинг */}
      <Navbar /> {/* меню на всех страницах */}
      <Routes> {/* список маршрутов */}
        <Route path="/" element={<Home />} /> {/* "/" -> главная */}
        <Route path="/masters" element={<Masters />} /> {/* "/masters" -> мастера */}
      </Routes> {/* конец списка */}
    </BrowserRouter> // конец роутинга
  ); // конец return
} // конец App

export default App; // отдаём наружу

// Ожидаемый результат: на странице «Мастера» — список мастеров и их должности.
