// Работа 2. Счётчик — Задача 1. Простейший счётчик
// Кнопка с числом 0. При каждом клике число увеличивается на 1 и показывается на самой кнопке.

import React, { useState } from "react"; // подключаем React и useState (чтобы компонент помнил число)

function CounterButton() { // создаём компонент «кнопка-счётчик»
  const [count, setCount] = useState(0); // память для числа: count сначала 0, setCount меняет его

  return ( // что показать на экране
    <button // начало кнопки
      onClick={() => setCount(count + 1)} // при клике увеличиваем число на 1 (стрелка нужна, т.к. передаём значение)
      className="px-4 py-2 bg-blue-500 text-white rounded-lg" // оформление: отступы, синий фон, белый текст, скруглённые углы
    > {/* конец открывающего тега button */}
      {count} {/* текст на кнопке — текущее число */}
    </button> // конец кнопки
  ); // конец return
} // конец компонента

export default CounterButton; // отдаём компонент наружу

// Как будет работать: кнопка сначала показывает 0, при кликах — 1, 2, 3 и т.д.
